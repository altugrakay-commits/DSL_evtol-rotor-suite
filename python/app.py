@st.cache_resource
def load_surrogate():
    ckpt = torch.load(str(THIS_DIR.parent / "models" / "surrogate.pt"), map_location="cpu", weights_only=False)
    model = Surrogate(width=ckpt["config"]["width"], depth=ckpt["config"]["depth"])
    model.load_state_dict(ckpt["state_dict"])
    model.eval()
    return model, ckpt["x_mean"], ckpt["x_std"], ckpt["y_mean"], ckpt["y_std"]

@st.cache_resource
def load_blade_mesh():
    """Read figures/blade.stl (binary STL) using pure numpy.

    Returns (vertices, faces): vertices is (N, 3) float32, faces is
    (M, 3) int32 indices into vertices.  The STL file was generated by
    CadQuery's exporters.export(), which produces binary STL by default.
    """
    path = THIS_DIR.parent / "figures" / "blade.stl"
    with open(path, "rb") as f:
        f.read(80)                                    # 80-byte header
        n_tri = int.from_bytes(f.read(4), "little")   # uint32 count
        raw   = f.read(n_tri * 50)                    # 50 bytes per tri

    arr    = np.frombuffer(raw, dtype=np.uint8).reshape(n_tri, 50)
    floats = arr[:, :48].copy().view(np.float32).reshape(n_tri, 12)
    verts  = floats[:, 3:].reshape(-1, 3)             # skip normals

    # Deduplicate vertices so faces are indices into a compact array
    rounded = np.round(verts.astype(np.float64), 6)
    unique, inverse = np.unique(rounded, axis=0, return_inverse=True)
    faces = inverse.reshape(-1, 3).astype(np.int32)
    return unique.astype(np.float32), faces

def predict_pinn(design, model, xm, xs, ym, ys):
    xn = (np.asarray(design) - xm) / xs
    with torch.no_grad():
        yn = model(torch.from_numpy(xn).float().unsqueeze(0)).numpy()[0]
    yp = yn * ys + ym
    for j in LOG_OUTPUTS:
        yp[j] = inv_signed_log1p(yp[j])
    for j, (lo, hi) in CLIP_RANGES.items():
        yp[j] = np.clip(yp[j], lo, hi)
    return dict(zip(OUT_KEYS, yp.tolist()))

